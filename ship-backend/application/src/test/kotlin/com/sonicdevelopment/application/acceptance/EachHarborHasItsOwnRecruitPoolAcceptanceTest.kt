package com.sonicdevelopment.application.acceptance

import com.sonicdevelopment.application.acceptance.fixtures.FakeDrivenPorts
import com.sonicdevelopment.application.acceptance.fixtures.FakeHarborTest
import com.sonicdevelopment.domain.model.Recruit
import com.sonicdevelopment.domain.model.values.HarborName
import com.sonicdevelopment.domain.ports.driving.harbor.HarborManagementPort
import com.sonicdevelopment.domain.service.RecruitPoolGenerator
import io.kotest.matchers.collections.shouldContainExactly
import io.kotest.matchers.collections.shouldHaveSize
import io.kotest.matchers.collections.shouldNotContain
import io.kotest.matchers.string.shouldNotBeBlank
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.test.web.client.TestRestTemplate
import org.springframework.test.context.TestPropertySource
import java.util.UUID

/**
 * Feature: Each Harbor has its own Recruit Pool.
 *
 * One Harbor ("Port Royal") on in-memory fakes; the pool is read over HTTP: `GET /web/recruits`. A second Harbor is
 * generated by a second generator, as no second process takes part (ADR-0003, ADR-0010).
 */
@FakeHarborTest
@TestPropertySource(properties = ["harbor.name=Port Royal"])
class EachHarborHasItsOwnRecruitPoolAcceptanceTest {

    @Autowired
    lateinit var restTemplate: TestRestTemplate

    @Autowired
    lateinit var fakes: FakeDrivenPorts

    @Autowired
    lateinit var harbor: HarborManagementPort

    @BeforeEach
    fun aFreshHarbor() {
        fakes.reset()
    }

    @Test
    fun `A Harbor offers five Recruits`() {
        harbor.openHarbor()

        val recruits = readPool()

        recruits shouldHaveSize 5
        recruits.forEach {
            it.name.shouldNotBeBlank()
            it.trait.shouldNotBeBlank()
        }
    }

    @Test
    fun `Two Harbors offer different Recruits`() {
        val portRoyal = (0 until 5).map { RecruitPoolGenerator(HarborName("Port Royal")).recruit(it) }
        val tortuga = (0 until 5).map { RecruitPoolGenerator(HarborName("Tortuga")).recruit(it) }

        portRoyal.map { it.id } .forEach { tortuga.map { r -> r.id } shouldNotContain it }
        portRoyal.map { it.name }.forEach { tortuga.map { r -> r.name } shouldNotContain it }
    }

    @Test
    fun `A Harbor opening again offers the same Recruits`() {
        // Given "Port Royal" offers Mittens, Patch, Saffron, Biscuit, Pepper
        val pinned = listOf("Mittens", "Patch", "Saffron", "Biscuit", "Pepper")
        val generator = RecruitPoolGenerator(HarborName("Port Royal"))
        pinned.forEachIndexed { ordinal, name ->
            fakes.recruits.rememberRecruit(ordinal, Recruit(generator.recruit(ordinal).id, name, "Fearless"))
        }

        // When it opens again
        harbor.openHarbor()

        // Then it offers exactly those Recruits
        readPool().map { it.name } shouldContainExactly pinned
        // And again after a second opening
        harbor.openHarbor()
        readPool().map { it.name } shouldContainExactly pinned
    }

    private data class RecruitBody(val id: UUID = UUID.randomUUID(), val name: String = "", val trait: String = "")

    private fun readPool(): List<RecruitBody> =
        restTemplate.getForEntity("/web/recruits", Array<RecruitBody>::class.java).body!!.toList()
}
